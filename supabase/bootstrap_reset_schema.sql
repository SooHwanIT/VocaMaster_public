create or replace function public.get_wrong_notes_summary()
returns table (
  word_id text,
  dataset_id text,
  wrong_count bigint,
  correct_count bigint,
  total_count bigint,
  accuracy_pct numeric,
  last_attempted_at timestamptz
)
language sql
security invoker
as $$
  select
    wal.word_id,
    wal.dataset_id,
    count(*) filter (where wal.is_correct = false) as wrong_count,
    count(*) filter (where wal.is_correct = true) as correct_count,
    count(*) as total_count,
    round(
      (
        count(*) filter (where wal.is_correct = true)::numeric
        / nullif(count(*), 0)
      ) * 100,
      1
    ) as accuracy_pct,
    max(wal.created_at) as last_attempted_at
  from public.word_attempt_logs wal
  where wal.user_id = auth.uid()
  group by wal.word_id, wal.dataset_id
  having count(*) filter (where wal.is_correct = false) > 0
  order by wrong_count desc, last_attempted_at desc;
$$;

