-- 4) XP 부여 RPC 함수
create or replace function public.add_xp(
  p_user_id uuid,
  p_xp integer,
  p_reason text,
  p_word_id text default null
)
returns jsonb as $$
declare
  v_actor uuid := auth.uid();
  v_new_xp integer;
  v_new_level integer;
  v_today date := current_date;
  v_last_date date;
  v_streak integer;
begin
  if v_actor is null then
    raise exception 'unauthorized';
  end if;

  if p_user_id is null or p_user_id <> v_actor then
    raise exception 'forbidden';
  end if;

  if p_xp is null or p_xp < 0 or p_xp > 100 then
    raise exception 'invalid xp amount';
  end if;

  if p_reason not in ('word_correct', 'word_mastered') then
    raise exception 'invalid xp reason';
  end if;

  if p_word_id is not null and length(trim(p_word_id)) = 0 then
    raise exception 'invalid word id';
  end if;

  insert into public.profiles (id)
  values (p_user_id)
  on conflict (id) do nothing;

  -- XP 로그 기록
  insert into public.xp_logs(user_id, xp_gained, reason, word_id)
  values (p_user_id, p_xp, p_reason, p_word_id);

  -- streak 계산
  select last_study_date, streak_days
  into v_last_date, v_streak
  from public.profiles
  where id = p_user_id
  for update;

  if v_last_date is null or v_last_date < v_today - interval '1 day' then
    v_streak := 1;
  elsif v_last_date = v_today - interval '1 day' then
    v_streak := coalesce(v_streak, 0) + 1;
  -- else same day: streak unchanged
  end if;

  -- total_xp 업데이트 + streak
  update public.profiles
  set
    total_xp = coalesce(total_xp, 0) + p_xp,
    last_study_date = v_today,
    streak_days = coalesce(v_streak, 1)
  where id = p_user_id
  returning total_xp into v_new_xp;

  -- 레벨 재계산
  select max(level) into v_new_level
  from public.level_rewards
  where required_xp <= v_new_xp;

  update public.profiles
  set current_level = coalesce(v_new_level, 1)
  where id = p_user_id;

  return jsonb_build_object(
    'total_xp', v_new_xp,
    'current_level', coalesce(v_new_level, 1),
    'streak_days', coalesce(v_streak, 1)
  );
end;
$$ language plpgsql security definer set search_path = public, pg_temp;

